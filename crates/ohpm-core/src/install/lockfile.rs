    #[test]
    fn roundtrip_and_version_gate() {
        let dir = TempDir::new().unwrap();
        let path = dir.path().join(LOCK_JSON);
        let lf = sample_lockfile();
        write_lockfile(&path, &lf).unwrap();

        let loaded = read_lockfile(&path).expect("load");
        assert_eq!(loaded.specifiers, lf.specifiers);
        assert_eq!(loaded.packages.len(), 2);
        let pkg = &loaded.packages["@ohos/foo@1.2.3"];
        assert_eq!(pkg.name, "@ohos/foo");
        assert_eq!(pkg.dependencies["@ohos/bar"], "1.0.0");

        // A v2 file is ignored.
        write(dir.path(), LOCK_JSON, "{ \"lockfileVersion\": 2 }");
        assert!(read_lockfile(&path).is_none());

        // A file without meta gets stableOrder=false.
        write(
            dir.path(),
            LOCK_JSON,
            r#"{ "lockfileVersion": 3, "specifiers": {}, "packages": {} }"#,
        );
        let loaded = read_lockfile(&path).expect("load v3 no meta");
        assert!(!loaded.meta_stable_order);
        assert!(loaded.meta_enable_unified_lockfile.is_none());
    }

    #[test]
    fn locker_flush_prunes() {
        let dir = TempDir::new().unwrap();
        write_lockfile(&dir.path().join(LOCK_JSON), &sample_lockfile()).unwrap();
        let mut locker = Locker::load(dir.path());
        assert!(locker.was_present);
        // Touch only `bar@latest`; `@ohos/foo@^1.2.0` must be pruned.
        locker.update_lock_spec("bar", "latest", "2.1.0");
        let mut pkg = LockPkg::new("bar", "2.1.0");
        pkg.registry_type = "ohpm".to_string();
        pkg.dependencies.insert("baz".to_string(), "1.0.0".to_string());
        pkg.dynamic_dependencies.insert("dyn".to_string(), "1.0.0".to_string());
        locker.update_lock_pkg("bar", "2.1.0", pkg);
        locker.flush().unwrap();

        let text = fs::read_to_string(dir.path().join(LOCK_JSON)).unwrap();
        assert!(text.contains("\"bar@latest\": \"bar@2.1.0\""));
        assert!(!text.contains("@ohos/foo"));
        assert!(!text.contains("2.0.0"));
        assert!(text.contains("\"dependencies\": {"));
        assert!(text.contains("\"dynamicDependencies\": {"));

        // A second flush with no writes leaves an empty package map -> the
        // file still exists, so it is written with empty maps.
        let mut locker2 = Locker::load(dir.path());
        locker2.flush().unwrap();
        let text2 = fs::read_to_string(dir.path().join(LOCK_JSON)).unwrap();
        assert!(text2.contains("\"specifiers\": {}"));
        assert!(text2.contains("\"packages\": {}"));
    }

